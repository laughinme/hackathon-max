"""What the service stores and how to delete it (MAX platform rules)."""

from __future__ import annotations


def policy() -> str:
    return (
        "🔒 <b>Ваши данные</b>\n\n"
        "<b>Что я храню</b>\n"
        "• ваш идентификатор в MAX и имя из профиля — чтобы знать, чьи это заявки;\n"
        "• дом, который вы выбрали, и роль (житель или диспетчер УО);\n"
        "• тексты заявок и историю их статусов;\n"
        "• черновик заявки, пока вы её оформляете.\n\n"
        "Телефон, адрес квартиры и паспортные данные я не запрашиваю. В жалобе "
        "в жилинспекцию ФИО и адрес вы вписываете сами, у меня они не остаются.\n\n"
        "<b>Зачем</b>\n"
        "Передать заявку в управляющую организацию, посчитать нормативный срок "
        "и сообщать вам о статусе.\n\n"
        "<b>Удаление</b>\n"
        "Кнопка ниже отвяжет вас от дома и ролей и сотрёт черновик. Заявки "
        "останутся у УО как обращения по дому, но без связи с вами — уведомлений "
        "по ним вы больше не получите.\n\n"
        "🧪 Сервис работает в тестовом режиме на демонстрационных данных."
    )


def confirm_forget() -> str:
    return (
        "🗑 <b>Удалить мои данные?</b>\n\n"
        "Я отвяжу вас от дома и ролей, сотру черновик и уберу связь с вашими "
        "заявками. Отменить это нельзя."
    )


def forgotten(tickets: int) -> str:
    detached = f"\nЗаявок, отвязанных от вас: {tickets}." if tickets else ""
    return (
        f"✅ <b>Данные удалены</b>{detached}\n\n"
        "Если захотите вернуться — нажмите /start."
    )
